#!/usr/bin/env python3
"""Write src/core/adif_world_110m.cpp from Natural Earth's ne_110m_land.geojson.

Natural Earth is in the public domain (naturalearthdata.com/about/terms-of-use,
read 2026-10-10). Get the file from github.com/nvkelso/natural-earth-vector
(geojson/ne_110m_land.geojson) and pass its path:

    python3 tools/gen_world_outline.py path/to/ne_110m_land.geojson
"""
import json
import pathlib
import sys

src = pathlib.Path(sys.argv[1])
data = json.loads(src.read_text(encoding="utf-8"))
rings = []
for feature in data["features"]:
    geometry = feature["geometry"]
    polygons = [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
    for polygon in polygons:
        outer = polygon[0]  # the land; 110m land has no lakes cut out that matter at this scale
        ring = []
        for lon, lat in outer:
            p = (round(lon * 100), round(lat * 100))
            if not ring or ring[-1] != p:
                ring.append(p)
        if len(ring) >= 3:
            rings.append(ring)

out = []
out.append("// Generated by tools/gen_world_outline.py from Natural Earth's ne_110m_land.geojson")
out.append("// (public domain, naturalearthdata.com). Do not edit by hand.")
out.append('#include "adif_world.h"')
out.append("")
out.append("namespace adif {")
out.append("namespace {")
out.append("")
out.append("// Longitude and latitude in hundredths of a degree, ring after ring.")
out.append("const short kLandPoints[] = {")
offsets = [0]
line = []
for ring in rings:
    for lon, lat in ring:
        line.append(f"{lon},{lat}")
        if len(line) == 12:
            out.append("    " + ", ".join(line) + ",")
            line = []
    offsets.append(offsets[-1] + len(ring))
if line:
    out.append("    " + ", ".join(line) + ",")
out.append("};")
out.append("const unsigned short kRingStart[] = {")
for i in range(0, len(offsets), 16):
    out.append("    " + ", ".join(str(o) for o in offsets[i:i + 16]) + ",")
out.append("};")
out.append("")
out.append("}  // namespace")
out.append("")
out.append("size_t landRingCount() { return sizeof kRingStart / sizeof kRingStart[0] - 1; }")
out.append("")
out.append("std::vector<std::pair<double, double>> landRing(size_t i) {")
out.append("    std::vector<std::pair<double, double>> out;")
out.append("    if (i >= landRingCount()) return out;")
out.append("    for (unsigned k = kRingStart[i]; k < kRingStart[i + 1]; ++k)")
out.append("        out.emplace_back(kLandPoints[2 * k] / 100.0, kLandPoints[2 * k + 1] / 100.0);")
out.append("    return out;")
out.append("}")
out.append("")
out.append("}  // namespace adif")
pathlib.Path("src/core/adif_world_110m.cpp").write_text("\n".join(out) + "\n")
print(f"{len(rings)} rings, {offsets[-1]} points")
