#!/usr/bin/env python3
"""Write src/core/adif_world_data.cpp from Natural Earth's GeoJSON layers.

Natural Earth is in the public domain (naturalearthdata.com/about/terms-of-use,
read 2026-10-10). Get these from github.com/nvkelso/natural-earth-vector
(geojson/) and pass the folder holding them:

    ne_110m_land, ne_50m_land                 land (the world view, zoomed in)
    ne_110m_lakes, ne_50m_lakes               lakes
    ne_50m_rivers_lake_centerlines            rivers, ranked 1 (major) to 6
    ne_50m_admin_0_boundary_lines_land        country borders on land
    ne_50m_admin_1_states_provinces_lines     state and province lines

    python3 tools/gen_world_outline.py path/to/folder
"""
import json
import pathlib
import sys

folder = pathlib.Path(sys.argv[1])


def shapes(name, polygons):
    """Every ring (polygons, holes included) or line, with Natural Earth's scalerank."""
    data = json.loads((folder / (name + ".geojson")).read_text(encoding="utf-8"))
    out = []
    for feature in data["features"]:
        g = feature["geometry"]
        if not g or not g.get("coordinates"):
            continue
        rank = feature["properties"].get("scalerank") or 0
        if g["type"] == "Polygon":
            parts = g["coordinates"]
        elif g["type"] == "MultiPolygon":
            parts = [ring for poly in g["coordinates"] for ring in poly]
        elif g["type"] == "LineString":
            parts = [g["coordinates"]]
        else:  # MultiLineString
            parts = g["coordinates"]
        for part in parts:
            pts = []
            for lon, lat in (c[:2] for c in part):
                p = (round(lon * 100), round(lat * 100))
                if not pts or pts[-1] != p:
                    pts.append(p)
            if len(pts) >= (3 if polygons else 2):
                out.append((pts, int(rank)))
    return out


layers = [("Land110", "ne_110m_land", True), ("Land50", "ne_50m_land", True), ("Lakes110", "ne_110m_lakes", True),
          ("Lakes50", "ne_50m_lakes", True), ("Rivers50", "ne_50m_rivers_lake_centerlines", False),
          ("Borders50", "ne_50m_admin_0_boundary_lines_land", False), ("States50", "ne_50m_admin_1_states_provinces_lines", False)]
out = ["// Generated by tools/gen_world_outline.py from Natural Earth's land, lakes, rivers and",
       "// boundary lines (public domain, naturalearthdata.com). Do not edit by hand.",
       '#include "adif_world.h"', "", "namespace adif {", "namespace {", "",
       "// Longitude and latitude in hundredths of a degree, shape after shape; kXStart[i] is shape i's",
       "// first point, kXRank[i] its Natural Earth scalerank (0 when the layer has none)."]
for name, source, polygons in layers:
    items = shapes(source, polygons)
    out.append(f"const short k{name}Points[] = {{")
    starts, ranks, row = [0], [], []
    for pts, rank in items:
        for lon, lat in pts:
            row.append(f"{lon},{lat}")
            if len(row) == 12:
                out.append("    " + ",".join(row) + ",")
                row = []
        starts.append(starts[-1] + len(pts))
        ranks.append(rank)
    if row:
        out.append("    " + ",".join(row) + ",")
    out.append("};")
    out.append(f"const unsigned k{name}Start[] = {{")
    for i in range(0, len(starts), 16):
        out.append("    " + ",".join(str(s) for s in starts[i:i + 16]) + ",")
    out.append("};")
    out.append(f"const unsigned char k{name}Rank[] = {{")
    for i in range(0, len(ranks), 32):
        out.append("    " + ",".join(str(r) for r in ranks[i:i + 32]) + ",")
    out.append("};")
    print(f"{name}: {len(items)} shapes, {starts[-1]} points")

out += ["", "struct Layer {", "    const short *points;", "    const unsigned *start;", "    const unsigned char *rank;", "    size_t count;", "};", ""]
out.append("Layer layer(MapLayer l) {")
out.append("    switch (l) {")
for name, _, _ in layers:
    out.append(f"        case MapLayer::{name}: return {{k{name}Points, k{name}Start, k{name}Rank, sizeof k{name}Rank}};")
out += ["    }", "    return {nullptr, nullptr, nullptr, 0};", "}", "", "}  // namespace", "",
        "size_t layerShapeCount(MapLayer l) { return layer(l).count; }", "",
        "std::vector<std::pair<double, double>> layerShape(MapLayer l, size_t i) {",
        "    Layer d = layer(l);",
        "    std::vector<std::pair<double, double>> out;",
        "    if (i >= d.count) return out;",
        "    for (unsigned k = d.start[i]; k < d.start[i + 1]; ++k) out.emplace_back(d.points[2 * k] / 100.0, d.points[2 * k + 1] / 100.0);",
        "    return out;", "}", "",
        "int layerShapeRank(MapLayer l, size_t i) {",
        "    Layer d = layer(l);",
        "    return i < d.count ? d.rank[i] : 0;", "}", "", "}  // namespace adif"]
pathlib.Path("src/core/adif_world_data.cpp").write_text("\n".join(out) + "\n")
