#!/usr/bin/env python3
"""Write src/core/adif_world_data.cpp from Natural Earth's land and border GeoJSON.

Natural Earth is in the public domain (naturalearthdata.com/about/terms-of-use,
read 2026-10-10). Get these from github.com/nvkelso/natural-earth-vector
(geojson/) and pass the folder holding them:

    ne_110m_land.geojson                    the world view
    ne_50m_land.geojson                     zoomed in
    ne_50m_admin_0_boundary_lines_land.geojson   country borders on land

    python3 tools/gen_world_outline.py path/to/folder
"""
import json
import pathlib
import sys

folder = pathlib.Path(sys.argv[1])


def lines(name, closed):
    data = json.loads((folder / name).read_text(encoding="utf-8"))
    out = []
    for feature in data["features"]:
        g = feature["geometry"]
        if g["type"] == "Polygon":
            parts = [g["coordinates"][0]]
        elif g["type"] == "MultiPolygon":
            parts = [p[0] for p in g["coordinates"]]
        elif g["type"] == "LineString":
            parts = [g["coordinates"]]
        else:  # MultiLineString
            parts = g["coordinates"]
        for part in parts:
            pts = []
            for lon, lat in part:
                p = (round(lon * 100), round(lat * 100))
                if not pts or pts[-1] != p:
                    pts.append(p)
            if len(pts) >= (3 if closed else 2):
                out.append(pts)
    return out


def table(name, shapes, out):
    out.append(f"const short k{name}Points[] = {{")
    starts = [0]
    row = []
    for shape in shapes:
        for lon, lat in shape:
            row.append(f"{lon},{lat}")
            if len(row) == 12:
                out.append("    " + ",".join(row) + ",")
                row = []
        starts.append(starts[-1] + len(shape))
    if row:
        out.append("    " + ",".join(row) + ",")
    out.append("};")
    out.append(f"const unsigned k{name}Start[] = {{")
    for i in range(0, len(starts), 16):
        out.append("    " + ",".join(str(s) for s in starts[i:i + 16]) + ",")
    out.append("};")
    return starts[-1]


sets = [("Land110", lines("ne_110m_land.geojson", True)), ("Land50", lines("ne_50m_land.geojson", True)),
        ("Borders50", lines("ne_50m_admin_0_boundary_lines_land.geojson", False))]
out = ["// Generated by tools/gen_world_outline.py from Natural Earth's ne_110m_land, ne_50m_land",
       "// and ne_50m_admin_0_boundary_lines_land (public domain, naturalearthdata.com). Do not edit by hand.",
       '#include "adif_world.h"', "", "namespace adif {", "namespace {", "",
       "// Longitude and latitude in hundredths of a degree, shape after shape; kXStart[i] is shape i's first point."]
for name, shapes in sets:
    n = table(name, shapes, out)
    print(f"{name}: {len(shapes)} shapes, {n} points")
out += ["", "template <size_t N, size_t S>",
        "std::vector<std::pair<double, double>> shape(const short (&points)[N], const unsigned (&start)[S], size_t i) {",
        "    std::vector<std::pair<double, double>> out;",
        "    if (i + 1 >= S) return out;",
        "    for (unsigned k = start[i]; k < start[i + 1]; ++k) out.emplace_back(points[2 * k] / 100.0, points[2 * k + 1] / 100.0);",
        "    return out;", "}", "", "}  // namespace", "",
        "size_t landRingCount(MapDetail d) {",
        "    return d == MapDetail::Fine ? sizeof kLand50Start / sizeof kLand50Start[0] - 1 : sizeof kLand110Start / sizeof kLand110Start[0] - 1;",
        "}", "",
        "std::vector<std::pair<double, double>> landRing(size_t i, MapDetail d) {",
        "    return d == MapDetail::Fine ? shape(kLand50Points, kLand50Start, i) : shape(kLand110Points, kLand110Start, i);",
        "}", "",
        "size_t borderLineCount() { return sizeof kBorders50Start / sizeof kBorders50Start[0] - 1; }", "",
        "std::vector<std::pair<double, double>> borderLine(size_t i) { return shape(kBorders50Points, kBorders50Start, i); }", "",
        "}  // namespace adif"]
pathlib.Path("src/core/adif_world_data.cpp").write_text("\n".join(out) + "\n")
